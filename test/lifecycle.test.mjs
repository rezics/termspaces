test('idempotent incremental apply preserves live task PID, state and manual layout', { timeout: 30000 }, async t => {
  const f = await fixture(t);
  const marker = join(f.dir, 'starts');
  f.doc.windows[0].panes[0].startup = { mode: 'on-create', argv: [process.execPath, '-e', 'require("fs").appendFileSync(process.argv[1],process.pid+"\\n");setInterval(()=>{},1000)', marker] };
  await f.save();
  await f.manager.apply(f.load);
  await until(async () => { try { return (await readFile(marker, 'utf8')).trim(); } catch { return false; } }, 'task start');
  const pid = Number((await readFile(marker, 'utf8')).trim());
  const before = await f.snapshot();
  assert.equal((await f.manager.apply(f.load)).completed.length, 0);
  f.doc.windows[0].panes.push({ id: 'second', shell: '/bin/bash' });
  f.doc.windows.push({ id: 'tests', panes: [{ id: 'main', shell: '/bin/bash' }] }); await f.save();
  await f.manager.apply(f.load);
  const state = await f.snapshot();
  assert.equal(state.sessions[0].windows.length, 2);
  assert.equal(state.sessions[0].windows[0].panes.length, 2);
  assert.equal(state.sessions[0].windows[0].panes[0].runtimeId, before.sessions[0].windows[0].panes[0].runtimeId);
  assert.equal((await readFile(marker, 'utf8')).trim().split('\n').length, 1);
  process.kill(pid, 0);
  const window = state.sessions[0].windows[0];
  await f.tmux.call(['select-layout', '-t', window.runtimeId, 'even-vertical']);
  const layout = await f.tmux.call(['display-message', '-p', '-t', window.runtimeId, '#{window_layout}']);
  f.doc.windows[0].panes[0].startup.argv = ['/bin/echo', 'new']; f.doc.windows.splice(1); await f.save();
  const changed = await f.manager.apply(f.load);
  assert.ok(changed.plan.deferred.some(d => /startup command changed/.test(d.reason)));
  assert.equal((await f.snapshot()).sessions[0].windows.length, 2);
  assert.equal(await f.tmux.call(['display-message', '-p', '-t', window.runtimeId, '#{window_layout}']), layout);
  process.kill(pid, 0);
});
test('literal format strings, semicolons, shell metacharacters and argv boundaries survive creation and rename', { timeout: 30000 }, async t => {
  const f = await fixture(t);
  const cwd = join(f.dir, 'path #{pid};'); await mkdir(cwd);
  const output = join(f.dir, 'args.json');
  const argv = ['a b', 'quote"', '$HOME', '`uname`', '$(touch SHOULD_NOT_EXIST)', ';', 'trailing;', '\\;', '#{pid}', '#(touch SHOULD_NOT_EXIST)'];
  f.doc.session.cwd = cwd; f.doc.session.name = 'Session #{pid};'; f.doc.windows[0].name = 'Window #{pid};';
  f.doc.windows[0].panes[0].sticky = false;
  f.doc.windows[0].panes[0].startup = { mode: 'on-create', argv: [process.execPath, '-e', 'require("fs").writeFileSync(process.argv[1],JSON.stringify(process.argv.slice(2)))', output, ...argv] };
  await f.save(); await f.manager.apply(f.load);
  await until(async () => { try { return await readFile(output, 'utf8'); } catch { return false; } }, 'argv output');
  assert.deepEqual(JSON.parse(await readFile(output, 'utf8')), argv);
  let state = await f.snapshot();
  assert.equal(state.sessions[0].name, f.doc.session.name);
  assert.equal(state.sessions[0].windows[0].name, f.doc.windows[0].name);
  f.doc.session.name = 'Renamed #{pid};'; f.doc.windows[0].name = 'Renamed #{pid};'; await f.save();
  await f.manager.apply(f.load); state = await f.snapshot();
  assert.equal(state.sessions[0].name, f.doc.session.name); assert.equal(state.sessions[0].windows[0].name, f.doc.windows[0].name);
  await assert.rejects(access(join(cwd, 'SHOULD_NOT_EXIST')));
});
test('concurrent processes apply once on the same socket', { timeout: 45000 }, async t => {
  const f = await fixture(t);
  const marker = join(f.dir, 'starts');
  f.doc.windows[0].panes[0].startup = { mode: 'on-create', argv: [process.execPath, '-e', 'require("fs").appendFileSync(process.argv[1],"started\\n")', marker] };
  await f.save();
  const results = await Promise.all([f.cli('apply'), f.cli('apply'), f.cli('apply')]);
  for (const r of results) assert.equal(r.code, 0, r.stdout + r.stderr);
  await until(async () => { try { return await readFile(marker, 'utf8'); } catch { return false; } });
  assert.equal(await readFile(marker, 'utf8'), 'started\n');
  const state = await f.snapshot(); assert.equal(state.sessions.length, 1); assert.equal(state.sessions[0].windows[0].panes.length, 1);
});
test('unowned collisions and inherited ownership never allow adoption or destructive clear', { timeout: 30000 }, async t => {
  const f = await fixture(t);
  await f.manager.ensureServer();
  await f.tmux.call(['new-session', '-d', '-s', 'Demo', '--', '/bin/sh', '-c', 'sleep 30']);
  await assert.rejects(() => f.manager.apply(f.load), { code: 'CONFLICT' });
  assert.equal((await f.snapshot()).sessions[0].owned, false);
  await f.tmux.call(['kill-session', '-t', '=Demo']);
  await f.manager.apply(f.load);
  const state = await f.snapshot(); const session = state.sessions[0]; const window = session.windows[0];
  // Parent tags must not make the manually created child owned.
  await f.tmux.option('w', window.runtimeId, '@ts-pane-owner', OWNER);
  await f.tmux.option('w', window.runtimeId, '@ts-pane-id', 'fake');
  await f.tmux.call(['split-window', '-d', '-t', window.runtimeId, '--', '/bin/sh', '-c', 'sleep 30']);
  assert.equal((await f.snapshot()).sessions[0].windows[0].panes[1].owned, false);
  await assert.rejects(() => f.manager.destroy('demo', false, f.load), { code: 'UNOWNED_DESCENDANTS' });
  assert.equal((await f.snapshot()).sessions.length, 1);
});
test('sticky shell survives exit, EOF and Ctrl-C; startup exit code stays recorded', { timeout: 30000 }, async t => {
  const f = await fixture(t);
  f.doc.windows[0].panes[0].startup = { mode: 'on-create', argv: ['/bin/sh', '-c', 'exit 7'] }; await f.save();
  await f.manager.apply(f.load);
  let pane = await until(async () => { const p = (await f.snapshot()).sessions[0].windows[0].panes[0]; return p.lastExit?.code === 7 && p.command === 'bash' ? p : false; }, 'startup exit followed by shell');
  await f.tmux.call(['send-keys', '-t', pane.runtimeId, 'exit', 'Enter']);
  await until(async () => (await f.snapshot()).sessions[0].windows[0].panes[0].shellExit !== null, 'shell exit');
  await f.tmux.call(['send-keys', '-t', pane.runtimeId, 'C-d']);
  await new Promise(resolve => setTimeout(resolve, 400));
  await f.tmux.call(['send-keys', '-t', pane.runtimeId, 'sleep 30', 'Enter']);
  await new Promise(resolve => setTimeout(resolve, 150));
  await f.tmux.call(['send-keys', '-t', pane.runtimeId, 'C-c']);
  const marker = join(f.dir, 'alive');
  await f.tmux.call(['send-keys', '-t', pane.runtimeId, `printf alive > '${marker}'`, 'Enter']);
  await until(async () => { try { return await readFile(marker, 'utf8') === 'alive'; } catch { return false; } }, 'shell after Ctrl-C');
  pane = (await f.snapshot()).sessions[0].windows[0].panes[0];
  assert.equal(pane.dead, false); assert.equal(pane.lastExit.code, 7);
  assert.equal((await f.manager.apply(f.load)).completed.length, 0);
});
test('clear/reset are scoped and require explicit confirmation; invalid reset preserves session', { timeout: 30000 }, async t => {
  const f = await fixture(t); await f.manager.apply(f.load);
  assert.equal(JSON.parse((await f.cli('clear', 'demo')).stdout).error.code, 'CONFIRMATION_REQUIRED');
  const before = (await f.snapshot()).sessions[0].runtimeId;
  f.doc.windows = []; await f.save();
  await assert.rejects(() => f.manager.destroy('demo', true, f.load), { code: 'INVALID_CONFIG' });
  assert.equal((await f.snapshot()).sessions[0].runtimeId, before);
  f.doc.windows = [{ id: 'fresh', panes: [{ id: 'main', shell: '/bin/bash' }] }]; await f.save();
  await f.manager.destroy('demo', true, f.load);
  assert.notEqual((await f.snapshot()).sessions[0].runtimeId, before);
  assert.equal((await f.snapshot()).sessions[0].windows[0].id, 'fresh');
  await f.manager.destroy('demo', false, f.load);
  assert.equal((await f.snapshot()).sessions.length, 0);
});
