import { mkdir, writeFile, lstat, readFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { homedir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { configHome, ToolError } from './config.js';
import { tmuxConfigPath } from './manager.js';
import { run } from './tmux.js';

// systemd performs its own quoting, specifier and environment expansion.
export const unitArg = (s: string): string => '"' + s.replaceAll('\\', '\\\\').replaceAll('"', '\\"').replaceAll('%', '%%').replaceAll('$', () => '$$').replaceAll('\n', '\\n').replaceAll('\r', '\\r') + '"';
export async function autostart(socketName: string, socket: string, config: string, enable: boolean): Promise<unknown> {
  const found = await run('/bin/sh', ['-c', 'command -v tmux']);
  if (found.code) throw new ToolError('DEPENDENCY_MISSING', 'tmux is not installed.');
  const tmux = found.stdout.trim();
  const unitDir = join(process.env.XDG_CONFIG_HOME || join(homedir(), '.config'), 'systemd/user');
  const serverName = `termspaces-server-${socketName}.service`;
  const applyName = `termspaces-apply-${socketName}.service`;
  const launcher = fileURLToPath(new URL('./cli.js', import.meta.url));
  const header = '# Generated by termspaces/v1\n';
  const server = `${header}[Unit]\nDescription=Termspaces tmux server (${socketName})\n\n[Service]\nType=simple\nUMask=0077\nExecStartPre=${unitArg(process.execPath)} ${unitArg(launcher)} --socket ${unitArg(socketName)} --socket-path ${unitArg(socket)} _prepare-server\nExecStart=${unitArg(tmux)} -D -S ${unitArg(socket)} -f ${unitArg(tmuxConfigPath)}\n\n[Install]\nWantedBy=default.target\n`;
  const apply = `${header}[Unit]\nDescription=Apply Termspaces boot workspaces (${socketName})\nRequires=${serverName}\nAfter=${serverName}\n\n[Service]\nType=oneshot\nUMask=0077\nExecStart=${unitArg(process.execPath)} ${unitArg(launcher)} --socket ${unitArg(socketName)} --socket-path ${unitArg(socket)} --config ${unitArg(resolve(config))} apply --autostart --wait-server\n\n[Install]\nWantedBy=default.target\n`;
  await mkdir(unitDir, { recursive: true });
  for (const [name, content] of [[serverName, server], [applyName, apply]]) {
    const path = join(unitDir, name!);
    try {
      const old = await lstat(path);
      if (old.isSymbolicLink()) throw new ToolError('UNIT_CONFLICT', `Refusing to overwrite symlink ${path}.`);
      if (!(await readFile(path, 'utf8')).startsWith(header)) throw new ToolError('UNIT_CONFLICT', `Refusing to overwrite a unit not generated by termspaces: ${path}.`);
    } catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
    await writeFile(path, content!, { mode: 0o600 });
  }
  if (enable) {
    for (const args of [['--user', 'daemon-reload'], ['--user', 'enable', serverName, applyName]]) {
      const r = await run('systemctl', args);
      if (r.code) throw new ToolError('SYSTEMD_ERROR', r.stderr.trim());
    }
  }
  return { files: [join(unitDir, serverName), join(unitDir, applyName)], enabled: enable, next: `Enable linger with loginctl enable-linger ${process.env.USER || '<user>'}. If a manually started server uses this socket, detach and migrate it deliberately before starting ${serverName}. Never restart the server service to apply YAML edits.`, configHome: configHome() };
}
